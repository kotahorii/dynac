type Generator struct {
	PkgPath string
	PkgName string
	Table   string
	PK      string
	SK      string
	Models  *model.Registry
}

func (g *Generator) Generate(queries []query.Query) ([]byte, error) {
	var buf bytes.Buffer
	imports, err := g.collectImports(queries)
	if err != nil {
		return nil, err
	}
	fmt.Fprintln(&buf, "// Code generated by dynac. DO NOT EDIT.")
	fmt.Fprintln(&buf)
	fmt.Fprintf(&buf, "package %s\n\n", g.PkgName)
	writeImports(&buf, imports)
	for _, q := range queries {
		code, err := g.generateQuery(q)
		if err != nil {
			return nil, err
		}
		buf.WriteString("\n")
		buf.WriteString(code)
		buf.WriteString("\n")
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt failed: %w", err)
	}
	return formatted, nil
}

type param struct {
	Name string
	Type string
	Hint string
}

type keyCond struct {
	Attr     string
	CondType partiql.CondType
	ParamIdx []int
}

func (g *Generator) generateQuery(q query.Query) (string, error) {
	if err := q.Validate(query.ValidateOptions{Table: g.Table, PK: g.PK, SK: g.SK}); err != nil {
		return "", err
	}
	switch {
	case isBatchPutQuery(q.Name):
		if q.Kind != query.KindExec {
			return "", fmt.Errorf("%s: BatchPut must be :exec", q.Name)
		}
		if _, ok := q.Stmt.(partiql.InsertStmt); !ok {
			return "", fmt.Errorf("%s: BatchPut requires INSERT", q.Name)
		}
	case isBatchDeleteQuery(q.Name):
		if q.Kind != query.KindExec {
			return "", fmt.Errorf("%s: BatchDelete must be :exec", q.Name)
		}
		if _, ok := q.Stmt.(partiql.DeleteStmt); !ok {
			return "", fmt.Errorf("%s: BatchDelete requires DELETE", q.Name)
		}
	case isBatchGetQuery(q.Name):
		return "", fmt.Errorf("%s: BatchGet is not supported yet", q.Name)
	}
	modelName, err := g.modelNameForQuery(q)
	if err != nil {
		return "", err
	}
	switch stmt := q.Stmt.(type) {
	case partiql.SelectStmt:
		return g.generateSelect(q, stmt, modelName)
	case partiql.InsertStmt:
		return g.generateInsert(q, stmt, modelName)
	case partiql.UpdateStmt:
		return g.generateUpdate(q, stmt, modelName)
	case partiql.DeleteStmt:
		return g.generateDelete(q, stmt, modelName)
	default:
		return "", fmt.Errorf("%s: unsupported statement", q.Name)
	}
}

func (g *Generator) generateSelect(q query.Query, stmt partiql.SelectStmt, modelName string) (string, error) {
	keyPK, keySK, err := g.resolveKeys(q)
	if err != nil {
		return "", err
	}
	conds := condMap(stmt.Where)
	typeHints := indexTypeHints(q.Annotations.Index)
	keyConds, params, err := g.buildKeyConds(modelName, keyPK, keySK, conds, typeHints)
	if err != nil {
		return "", err
	}
	returnType := modelName
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s :%s\n", q.Name, kindString(q.Kind))
	fmt.Fprintf(&buf, "func (q *Queries) %s(ctx context.Context", q.Name)
	for _, p := range params {
		fmt.Fprintf(&buf, ", %s %s", p.Name, p.Type)
	}
	if q.Kind == query.KindMany {
		fmt.Fprintf(&buf, ") ([]%s, error) {\n", returnType)
	} else {
		fmt.Fprintf(&buf, ") (%s, error) {\n", returnType)
	}
	valueVars := make([]string, 0, len(params))
	for i, p := range params {
		valVar := fmt.Sprintf("v%d", i)
		valueVars = append(valueVars, valVar)
		if p.Hint != "" {
			fmt.Fprintf(&buf, "\t%s, err := q.marshalValueAs(%s, %q)\n", valVar, p.Name, p.Hint)
		} else {
			fmt.Fprintf(&buf, "\t%s, err := q.marshalValue(%s)\n", valVar, p.Name)
		}
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		if q.Kind == query.KindMany {
			fmt.Fprintf(&buf, "\t\treturn nil, invalidErr(err)\n")
		} else {
			fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", returnType)
		}
		fmt.Fprintf(&buf, "\t}\n")
		if i == len(params)-1 {
			fmt.Fprintln(&buf)
		}
	}
	useGet := q.Kind == query.KindOne && q.Annotations.Index == nil
	if useGet {
		fmt.Fprintf(&buf, "\tout, err := q.Client.GetItem(ctx, &dynamodb.GetItemInput{\n")
		fmt.Fprintf(&buf, "\t\tTableName: &q.Table,\n")
		fmt.Fprintf(&buf, "\t\tKey: map[string]types.AttributeValue{\n")
		for i, attr := range append(append([]string{}, keyPK...), keySK...) {
			fmt.Fprintf(&buf, "\t\t\t%q: %s,\n", attr, valueVars[i])
		}
		fmt.Fprintf(&buf, "\t\t},\n")
		fmt.Fprintf(&buf, "\t\tConsistentRead: ptrBool(true),\n")
		fmt.Fprintf(&buf, "\t})\n")
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, normalizeError(err)\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tif out.Item == nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, ErrNotFound\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tvar res %s\n", returnType)
		fmt.Fprintf(&buf, "\tif err := q.unmarshal(out.Item, &res); err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\treturn res, nil\n")
		fmt.Fprintf(&buf, "}\n")
		return buf.String(), nil
	}
	nameMap, valMap, expr := buildKeyExpression(keyConds)
	fmt.Fprintf(&buf, "\tkeyCond := %q\n", expr)
	fmt.Fprintf(&buf, "\texprNames := map[string]string{\n")
	for _, name := range sortedKeys(nameMap) {
		fmt.Fprintf(&buf, "\t\t%q: %q,\n", name, nameMap[name])
	}
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\texprVals := map[string]types.AttributeValue{\n")
	for _, name := range sortedKeys(valMap) {
		fmt.Fprintf(&buf, "\t\t%q: %s,\n", name, valMap[name])
	}
	fmt.Fprintf(&buf, "\t}\n")
	if q.Kind == query.KindOne {
		fmt.Fprintf(&buf, "\tlimit := int32(2)\n")
	}
	fmt.Fprintf(&buf, "\tinput := &dynamodb.QueryInput{\n")
	fmt.Fprintf(&buf, "\t\tTableName: &q.Table,\n")
	fmt.Fprintf(&buf, "\t\tKeyConditionExpression: &keyCond,\n")
	fmt.Fprintf(&buf, "\t\tExpressionAttributeNames: exprNames,\n")
	fmt.Fprintf(&buf, "\t\tExpressionAttributeValues: exprVals,\n")
	if q.Annotations.Index != nil {
		fmt.Fprintf(&buf, "\t\tIndexName: func() *string { v := %q; return &v }(),\n", q.Annotations.Index.Name)
		fmt.Fprintf(&buf, "\t\tConsistentRead: ptrBool(false),\n")
	}
	switch q.Kind {
	case query.KindOne:
		fmt.Fprintf(&buf, "\t\tLimit: &limit,\n")
	case query.KindMany:
		limit := effectiveLimit(q, stmt)
		if limit != nil {
			fmt.Fprintf(&buf, "\t\tLimit: func() *int32 { v := int32(%d); return &v }(),\n", *limit)
		}
	}
	fmt.Fprintf(&buf, "\t}\n")
	if q.Kind == query.KindOne {
		fmt.Fprintf(&buf, "\tout, err := q.Client.Query(ctx, input)\n")
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, normalizeError(err)\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tif len(out.Items) == 0 {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, ErrNotFound\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tif len(out.Items) > 1 {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, ErrInvalid\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tvar res %s\n", returnType)
		fmt.Fprintf(&buf, "\tif err := q.unmarshal(out.Items[0], &res); err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", returnType)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\treturn res, nil\n")
		fmt.Fprintf(&buf, "}\n")
		return buf.String(), nil
	}
	fmt.Fprintf(&buf, "\tvar res []%s\n", returnType)
	limit := effectiveLimit(q, stmt)
	if limit != nil {
		fmt.Fprintf(&buf, "\tmax := int32(%d)\n", *limit)
	}
	fmt.Fprintf(&buf, "\tp := dynamodb.NewQueryPaginator(q.Client, input)\n")
	fmt.Fprintf(&buf, "\tfor p.HasMorePages() {\n")
	fmt.Fprintf(&buf, "\t\tpage, err := p.NextPage(ctx)\n")
	fmt.Fprintf(&buf, "\t\tif err != nil {\n")
	fmt.Fprintf(&buf, "\t\t\treturn nil, normalizeError(err)\n")
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t\tfor _, item := range page.Items {\n")
	fmt.Fprintf(&buf, "\t\t\tvar row %s\n", returnType)
	fmt.Fprintf(&buf, "\t\t\tif err := q.unmarshal(item, &row); err != nil {\n")
	fmt.Fprintf(&buf, "\t\t\t\treturn nil, invalidErr(err)\n")
	fmt.Fprintf(&buf, "\t\t\t}\n")
	fmt.Fprintf(&buf, "\t\t\tres = append(res, row)\n")
	if limit != nil {
		fmt.Fprintf(&buf, "\t\t\tif int32(len(res)) >= max {\n")
		fmt.Fprintf(&buf, "\t\t\t\treturn res[:max], nil\n")
		fmt.Fprintf(&buf, "\t\t\t}\n")
	}
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn res, nil\n")
	fmt.Fprintf(&buf, "}\n")
	return buf.String(), nil
}

func (g *Generator) generateInsert(q query.Query, stmt partiql.InsertStmt, modelName string) (string, error) {
	_ = stmt
	if isBatchPutQuery(q.Name) {
		return g.generateBatchPut(q, modelName)
	}
	paramName := safeLowerCamel(modelName)
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s :%s\n", q.Name, kindString(q.Kind))
	fmt.Fprintf(&buf, "func (q *Queries) %s(ctx context.Context, %s %s) error {\n", q.Name, paramName, modelName)
	fmt.Fprintf(&buf, "\tav, err := q.marshal(%s)\n", paramName)
	fmt.Fprintf(&buf, "\tif err != nil {\n")
	fmt.Fprintf(&buf, "\t\treturn invalidErr(err)\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\tinput := &dynamodb.PutItemInput{\n")
	fmt.Fprintf(&buf, "\t\tTableName: &q.Table,\n")
	fmt.Fprintf(&buf, "\t\tItem: av,\n")
	fmt.Fprintf(&buf, "\t}\n")
	if isCreateQuery(q.Name) {
		fmt.Fprintf(&buf, "\tcond := \"attribute_not_exists(#pk)\"\n")
		fmt.Fprintf(&buf, "\texprNames := map[string]string{\n")
		fmt.Fprintf(&buf, "\t\t\"#pk\": %q,\n", g.PK)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tinput.ConditionExpression = &cond\n")
		fmt.Fprintf(&buf, "\tinput.ExpressionAttributeNames = exprNames\n")
	}
	fmt.Fprintf(&buf, "\t_, err = q.Client.PutItem(ctx, input)\n")
	fmt.Fprintf(&buf, "\tif isConditionalFailed(err) {\n")
	fmt.Fprintf(&buf, "\t\treturn ErrConflict\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn normalizeError(err)\n")
	fmt.Fprintf(&buf, "}\n")
	return buf.String(), nil
}

func (g *Generator) generateBatchPut(q query.Query, modelName string) (string, error) {
	paramName := pluralize(safeLowerCamel(modelName))
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s :%s\n", q.Name, kindString(q.Kind))
	fmt.Fprintf(&buf, "func (q *Queries) %s(ctx context.Context, %s []%s) error {\n", q.Name, paramName, modelName)
	fmt.Fprintf(&buf, "\tif len(%s) == 0 {\n", paramName)
	fmt.Fprintf(&buf, "\t\treturn nil\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treqs := make([]types.WriteRequest, 0, len(%s))\n", paramName)
	fmt.Fprintf(&buf, "\tfor _, item := range %s {\n", paramName)
	fmt.Fprintf(&buf, "\t\tav, err := q.marshal(item)\n")
	fmt.Fprintf(&buf, "\t\tif err != nil {\n")
	fmt.Fprintf(&buf, "\t\t\treturn invalidErr(err)\n")
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t\treqs = append(reqs, types.WriteRequest{\n")
	fmt.Fprintf(&buf, "\t\t\tPutRequest: &types.PutRequest{Item: av},\n")
	fmt.Fprintf(&buf, "\t\t})\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn q.batchWrite(ctx, reqs)\n")
	fmt.Fprintf(&buf, "}\n")
	return buf.String(), nil
}

func (g *Generator) generateUpdate(q query.Query, stmt partiql.UpdateStmt, modelName string) (string, error) {
	pk, sk, err := g.resolveKeys(q)
	if err != nil {
		return "", err
	}
	params, setParams, err := g.buildUpdateParams(modelName, pk, sk, stmt)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s :%s\n", q.Name, kindString(q.Kind))
	fmt.Fprintf(&buf, "func (q *Queries) %s(ctx context.Context", q.Name)
	for _, p := range params {
		fmt.Fprintf(&buf, ", %s %s", p.Name, p.Type)
	}
	if q.Kind == query.KindOne {
		fmt.Fprintf(&buf, ") (%s, error) {\n", modelName)
	} else {
		fmt.Fprintf(&buf, ") error {\n")
	}
	keyCount := len(pk) + len(sk)
	keyParams := params[:keyCount]
	keyVars := make([]string, 0, len(keyParams))
	for i, p := range keyParams {
		valVar := fmt.Sprintf("k%d", i)
		keyVars = append(keyVars, valVar)
		fmt.Fprintf(&buf, "\t%s, err := q.marshalValue(%s)\n", valVar, p.Name)
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		if q.Kind == query.KindOne {
			fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", modelName)
		} else {
			fmt.Fprintf(&buf, "\t\treturn invalidErr(err)\n")
		}
		fmt.Fprintf(&buf, "\t}\n")
		if i == len(keyParams)-1 && len(setParams) > 0 {
			fmt.Fprintln(&buf)
		}
	}
	for i, p := range setParams {
		valVar := fmt.Sprintf("v%d", i)
		fmt.Fprintf(&buf, "\t%s, err := q.marshalValue(%s)\n", valVar, p.Name)
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		if q.Kind == query.KindOne {
			fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", modelName)
		} else {
			fmt.Fprintf(&buf, "\t\treturn invalidErr(err)\n")
		}
		fmt.Fprintf(&buf, "\t}\n")
		if i == len(setParams)-1 {
			fmt.Fprintln(&buf)
		}
	}
	alias := map[string]string{}
	assign := func(attr string) string {
		if v, ok := alias[attr]; ok {
			return v
		}
		key := fmt.Sprintf("#n%d", len(alias))
		alias[attr] = key
		return key
	}
	for _, p := range setParams {
		assign(p.Attr)
	}
	assign(g.PK)
	fmt.Fprintf(&buf, "\tupdateExpr := \"SET ")
	for i, p := range setParams {
		if i > 0 {
			buf.WriteString(", ")
		}
		buf.WriteString(fmt.Sprintf("%s = :v%d", alias[p.Attr], i))
	}
	fmt.Fprintf(&buf, "\"\n")
	fmt.Fprintf(&buf, "\tcond := \"attribute_exists(%s)\"\n", alias[g.PK])
	exprNames := invertAliasMap(alias)
	fmt.Fprintf(&buf, "\texprNames := map[string]string{\n")
	for _, name := range sortedKeys(exprNames) {
		fmt.Fprintf(&buf, "\t\t%q: %q,\n", name, exprNames[name])
	}
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\texprVals := map[string]types.AttributeValue{\n")
	for i := range setParams {
		fmt.Fprintf(&buf, "\t\t%q: v%d,\n", fmt.Sprintf(":v%d", i), i)
	}
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\tinput := &dynamodb.UpdateItemInput{\n")
	fmt.Fprintf(&buf, "\t\tTableName: &q.Table,\n")
	fmt.Fprintf(&buf, "\t\tKey: map[string]types.AttributeValue{\n")
	for i, attr := range append(append([]string{}, pk...), sk...) {
		fmt.Fprintf(&buf, "\t\t\t%q: %s,\n", attr, keyVars[i])
	}
	fmt.Fprintf(&buf, "\t\t},\n")
	fmt.Fprintf(&buf, "\t\tUpdateExpression: &updateExpr,\n")
	fmt.Fprintf(&buf, "\t\tConditionExpression: &cond,\n")
	fmt.Fprintf(&buf, "\t\tExpressionAttributeNames: exprNames,\n")
	fmt.Fprintf(&buf, "\t\tExpressionAttributeValues: exprVals,\n")
	if q.Kind == query.KindOne {
		rev := returnValueConst(stmt.Returning)
		fmt.Fprintf(&buf, "\t\tReturnValues: %s,\n", rev)
	}
	fmt.Fprintf(&buf, "\t}\n")
	if q.Kind == query.KindOne {
		fmt.Fprintf(&buf, "\tout, err := q.Client.UpdateItem(ctx, input)\n")
		fmt.Fprintf(&buf, "\tif isConditionalFailed(err) {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, ErrNotFound\n", modelName)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tif err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, normalizeError(err)\n", modelName)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tif out.Attributes == nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, ErrNotFound\n", modelName)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\tvar res %s\n", modelName)
		fmt.Fprintf(&buf, "\tif err := q.unmarshal(out.Attributes, &res); err != nil {\n")
		fmt.Fprintf(&buf, "\t\treturn %s{}, invalidErr(err)\n", modelName)
		fmt.Fprintf(&buf, "\t}\n")
		fmt.Fprintf(&buf, "\treturn res, nil\n")
		fmt.Fprintf(&buf, "}\n")
		return buf.String(), nil
	}
	fmt.Fprintf(&buf, "\t_, err = q.Client.UpdateItem(ctx, input)\n")
	fmt.Fprintf(&buf, "\tif isConditionalFailed(err) {\n")
	fmt.Fprintf(&buf, "\t\treturn ErrNotFound\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn normalizeError(err)\n")
	fmt.Fprintf(&buf, "}\n")
	return buf.String(), nil
}

